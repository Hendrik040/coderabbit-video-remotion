import {readFile, readdir, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {compile} from '@tailwindcss/node';
import {Scanner} from '@tailwindcss/oxide';
import postcss from 'postcss';

const root = fileURLToPath(new URL('../..', import.meta.url));
// Keep every fixture PR and its meaning, but omit backend fields the source UI
// never reads. The untouched upstream payload remains checked in for provenance.
const triageSource = path.join(root, 'studio/src/products/triage/source');
const originalPayload = JSON.parse(await readFile(path.join(triageSource, 'triageProductMockPayload.json'), 'utf8'));
const fixtureKeys = ['id', 'repository', 'number', 'title', 'url', 'changeStackPath', 'priority', 'author', 'reviewDecision', 'reviewDepth', 'securityRisk', 'reviewEffort', 'blockingPullRequestCount', 'workflowState', 'nextAction', 'project', 'changeType', 'isDraft'];
const motionPayload = originalPayload.map(row => ({...Object.fromEntries(fixtureKeys.map(key => [key, row[key]])),
  author: row.author ? {displayName: row.author.displayName, login: row.author.login} : null,
  nextAction: {kind: row.nextAction.kind}, securityRisk: row.securityRisk ? {level: row.securityRisk.level} : null,
}));
await writeFile(path.join(triageSource, 'triageProductMockPayload.motion.json'), JSON.stringify(motionPayload) + '\n');
const directory = path.join(root, 'studio/src/products/change-stack/source');
const files = (await readdir(directory)).filter(name => /\.(tsx|ts)$/.test(name));
const contents = await Promise.all(files.map(name => readFile(path.join(directory, name), 'utf8')));
const triageDirectory = path.join(root, 'studio/src/products/triage/source');
const triageFiles = (await readdir(triageDirectory)).filter(name => /\.(tsx|ts)$/.test(name));
const triageContents = await Promise.all(triageFiles.map(name => readFile(path.join(triageDirectory, name), 'utf8')));
const scanner = new Scanner({});
const candidates = scanner.scanFiles([...contents, ...triageContents].map(content => ({content, extension: 'tsx'})));
const compiler = await compile(`
@import 'tailwindcss' theme(static);
@import './studio/src/products/change-stack/source/carrotTheme.css' theme(static);
@import './studio/src/products/change-stack/source/carrotScales.css' theme(static);
@theme { --font-sans: Geist, sans-serif; --font-mono: Hack, monospace; --font-cui-sans: Geist, sans-serif; --font-cui-mono: Hack, monospace; }
`, {base: root, onDependency() {}});
const css = postcss.parse(compiler.build(candidates));
// Scope preflight, tokens, and utilities to the product. Unwrap Tailwind layers so
// the editor's unlayered element defaults cannot override the product utilities.
css.walkAtRules('layer', rule => rule.nodes ? rule.replaceWith(...rule.nodes) : rule.remove());
css.walkRules(rule => {
  if (rule.parent.type === 'rule' || rule.selector.includes('&')) return;
  for (let parent = rule.parent; parent; parent = parent.parent) if (parent.type === 'atrule' && /keyframes/.test(parent.name)) return;
  rule.selectors = rule.selectors.map(selector => {
    if (selector === ':root' || selector === ':host' || selector === 'html') return '.product-source';
    if (selector.startsWith('[data-theme=')) return `:where(.product-source)${selector}`;
    return `:where(.product-source) ${selector}`;
  });
});
css.walkComments(comment => {if (!comment.text.startsWith('!')) comment.remove();});
await writeFile(path.join(directory, '../utilities.generated.css'), `/* Generated by studio/scripts/build-product-styles.mjs. Do not edit. */\n${css.toString().trimEnd()}\n`);

// Keep the upstream stylesheet for provenance, ship only selectors this fixture uses.
const names = new Set(['heroRoot', ...contents.flatMap(content => [...content.matchAll(/styles\.([\w]+)/g)].map(match => match[1]))]);
const hero = postcss.parse(await readFile(path.join(directory, 'HomeHero.module.css'), 'utf8'));
hero.walkRules(rule => {
  const selectors = rule.selectors.filter(selector => [...selector.matchAll(/\.([a-zA-Z][\w-]*)/g)].some(match => names.has(match[1])));
  if (selectors.length) rule.selectors = selectors; else rule.remove();
});
hero.walkAtRules(rule => {if (rule.nodes && !rule.nodes.length) rule.remove();});
hero.walkComments(comment => comment.remove());
await writeFile(path.join(directory, 'HomeHero.motion.module.css'), `/* Generated subset of the original HomeHero.module.css. */\n${hero.toString().trimEnd()}\n`);
console.log(`Product styles: ${candidates.length} scanned candidates; ${Buffer.byteLength(css.toString())} bytes of scoped CSS.`);
